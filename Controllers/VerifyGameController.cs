        private int[][] GeneratePuzzleBoard(int size, int difficulty)
        {
            int totalCells = size * size;
            var target = new int[size][];
            int counter = 1;
            for (int r = 0; r < size; r++)
            {
                target[r] = new int[size];
                for (int c = 0; c < size; c++)
                {
                    target[r][c] = counter++;
                }
            }
            target[size - 1][size - 1] = 0;

            int steps = 20 + difficulty * 2 + (size == 4 ? 30 : 0);
            steps = Math.Min(steps, size == 4 ? 400 : 200);

            var puzzle = target.Select(row => row.ToArray()).ToArray();

            int emptyRow = size - 1;
            int emptyCol = size - 1;

            int lastMove = -1;
            for (int s = 0; s < steps; s++)
            {
                var moves = GetValidMoves(emptyRow, emptyCol, size, lastMove);
                if (moves.Count == 0) break;

                var move = moves[_random.Next(moves.Count)];
                lastMove = move.direction;

                int newRow = emptyRow + move.dRow;
                int newCol = emptyCol + move.dCol;

                puzzle[emptyRow][emptyCol] = puzzle[newRow][newCol];
                puzzle[newRow][newCol] = 0;

                emptyRow = newRow;
                emptyCol = newCol;
            }

            return puzzle;
        }

        private List<(int dRow, int dCol, int direction)> GetValidMoves(int row, int col, int size, int lastMove)
        {
            var moves = new List<(int, int, int)>();
            int[][] directions = new int[][]
            {
                new int[] { -1, 0, 0 },
                new int[] { 1, 0, 1 },
                new int[] { 0, -1, 2 },
                new int[] { 0, 1, 3 }
            };

            int opposite = lastMove == 0 ? 1 : lastMove == 1 ? 0 : lastMove == 2 ? 3 : lastMove == 3 ? 2 : -1;

            foreach (var d in directions)
            {
                int newRow = row + d[0];
                int newCol = col + d[1];
                if (newRow >= 0 && newRow < size && newCol >= 0 && newCol < size)
                {
                    if (d[2] != opposite)
                    {
                        moves.Add((d[0], d[1], d[2]));
                    }
                }
            }

            return moves;
        }

